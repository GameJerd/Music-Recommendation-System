"""Evaluate the content engine without user data: list-quality proxies over random seed tracks.

Usage: python scripts/evaluate.py [--n-seeds 2000]
Compares feature/re-ranking variants (ablations) on the same seeds and writes reports/content_eval.{md,csv}.
Genre match is a fair check only for variants whose features exclude genre; otherwise it is circular.
"""
import argparse
import time
from datetime import datetime, timezone

import numpy as np
import pandas as pd
from sklearn.preprocessing import normalize

from recsys.config import DEFAULT_CONFIG, load_config, resolve
from recsys.data.loaders import attach_genres, load_artist_genres, load_tracks
from recsys.engines.content import ContentEngine
from recsys.eval.metrics import Catalog, list_metrics
from recsys.features.audio import audio_block
from recsys.features.build import build_content

# name: (block weights, artist_cap, popularity_boost)
VARIANTS = {
    "audio only":                   ({"audio": 0.5, "genre": 0, "decade": 0}, 0, 0.0),
    "audio + decade":               ({"audio": 0.5, "genre": 0, "decade": 0.15}, 0, 0.0),
    "audio + genre":                ({"audio": 0.5, "genre": 0.35, "decade": 0}, 0, 0.0),
    "all blocks (Phase 1)":         ({"audio": 0.5, "genre": 0.35, "decade": 0.15}, 0, 0.0),
    "all blocks + artist cap 2":    ({"audio": 0.5, "genre": 0.35, "decade": 0.15}, 2, 0.0),
    "all + cap 2 + popularity 0.1": ({"audio": 0.5, "genre": 0.35, "decade": 0.15}, 2, 0.1),
}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", default=DEFAULT_CONFIG)
    ap.add_argument("--n-seeds", type=int)
    args = ap.parse_args()
    cfg = load_config(args.config)
    k, n_seeds = cfg["eval"]["k"], args.n_seeds or cfg["eval"]["n_seeds"]

    raw = resolve(cfg, "raw")
    tracks = attach_genres(load_tracks(raw), load_artist_genres(raw)).rename(columns={"id": "track_id"})
    cat = Catalog(genres=[set(g) for g in tracks["genres"]], decade=(tracks["year"].to_numpy() // 10) * 10,
                  artist=tracks["artists"].map(lambda a: a[0]).to_numpy(),
                  popularity=tracks["popularity"].to_numpy(), audio_unit=normalize(audio_block(tracks)))
    rng = np.random.default_rng(cfg["seed"])
    has_genre = np.flatnonzero(tracks["genres"].map(len).to_numpy() > 0)
    seeds = rng.choice(has_genre, size=n_seeds, replace=False)
    print(f"tier {cfg['scale']['tier']} | catalog {len(tracks):,} tracks | {n_seeds:,} random seed tracks with genres "
          f"| k={k} | data layer: catalog only, no user data")

    # reference: k random catalog tracks per seed, to read the proxies against chance
    rand = [rng.choice(len(tracks), size=k, replace=False) for _ in seeds]
    m = pd.DataFrame([list_metrics(s, list(r), cat) for s, r in zip(seeds, rand)]).mean().to_dict()
    rows = [{"variant": "random tracks (reference)", "genre_in_features": False, **m,
             "coverage": len(set(np.concatenate(rand))) / len(tracks), "latency_ms_p50": np.nan,
             "latency_ms_p95": np.nan}]
    for name, (weights, cap, boost) in VARIANTS.items():
        X, _ = build_content(tracks, weights)
        eng = ContentEngine(X, tracks, cfg["recommend"]["candidates"], cap, boost)
        per_seed, recommended, lat = [], set(), []
        for s in seeds:
            t0 = time.perf_counter()
            recs = eng.similar(tracks["track_id"].iat[s], k)
            lat.append((time.perf_counter() - t0) * 1000)
            rows_ = [eng.row[r.track_id] for r in recs]
            recommended.update(rows_)
            per_seed.append(list_metrics(s, rows_, cat))
        m = pd.DataFrame(per_seed).mean().to_dict()
        rows.append({"variant": name, "genre_in_features": weights["genre"] > 0, **m,
                     "coverage": len(recommended) / len(tracks), "latency_ms_p50": float(np.median(lat)),
                     "latency_ms_p95": float(np.percentile(lat, 95))})
        print(f"  done: {name}")

    table = pd.DataFrame(rows)
    shown = table.copy()
    shown["genre_match"] = [f"{g:.3f}" + (" (circular)" if c else "") for g, c in
                            zip(table["genre_match"], table["genre_in_features"])]
    shown = shown.drop(columns="genre_in_features")
    text = shown.to_string(index=False, float_format=lambda x: f"{x:.3f}")
    print("\n" + text)

    out = resolve(cfg, "reports")
    out.mkdir(parents=True, exist_ok=True)
    table.to_csv(out / "content_eval.csv", index=False)
    (out / "content_eval.md").write_text(
        f"# Content engine evaluation\n\nGenerated by `python scripts/evaluate.py` on "
        f"{datetime.now(timezone.utc):%Y-%m-%d %H:%M} UTC. Tier {cfg['scale']['tier']}, catalog {len(tracks):,} "
        f"tracks, {n_seeds:,} random seed tracks (seed {cfg['seed']}), top-{k} similar per seed.\n\n"
        "**No user data.** These are proxies for what kind of list the engine returns, not accuracy. "
        "Genre match is a fair check only where genre is not a feature (marked circular otherwise).\n\n"
        f"```text\n{text}\n```\n\nColumns: share of recs sharing a genre / decade / primary artist with the seed; "
        "distinct primary artists in the list; audio diversity = 1 - mean pairwise cosine of standardised audio "
        "features; mean dataset popularity (0-100); coverage = share of the catalog recommended for any seed; "
        "latency of one `similar` call in-process.\n", encoding="utf-8")
    print(f"\n-> {out / 'content_eval.md'}, {out / 'content_eval.csv'}")


if __name__ == "__main__":
    main()
